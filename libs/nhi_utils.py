def get_visit(database, row):
    if string_utils.xstr(row["RegistType"]) in TOUR_TYPE:  # 巡迴醫療不可申報初診照護
        return None

    if (
        string_utils.xstr(row["RegistType"]) in LONG_TERM_CARE
    ):  # 2025-12-19 照護機構中醫照護
        return None

    if (
        string_utils.xstr(row["TreatType"]) in AUXILIARY_CARE_TREAT
    ):  # 腦血管疾病, 小兒氣喘, 小兒腦麻不可申報初診照護
        return None

    if string_utils.xstr(row["TreatType"]) in IMPROVE_CARE_TREAT:  # 2021-10-12 加強照護
        return None

    if (
        string_utils.xstr(row["Injury"]) in OCCUPATIONAL_INJURY_TYPE
    ):  # 2022-11-06 職業災害
        return None

    if (
        string_utils.xstr(row["Share"]) in INFECTIOUS_INJURY_TYPE
        or string_utils.xstr(row["Injury"]) in INFECTIOUS_INJURY_TYPE
    ):  # 法定傳染病通報隔離 不得申報初診照護
        return None

    age_year, _ = date_utils.get_age(row["Birthday"], row["CaseDate"])
    if (
        age_year is not None and age_year < 4
    ):  # 未滿四歲兒童不可申報初診照護 (診察費已加成) 2023.08.16 健保署北區業務組通知
        return None

    patient_key = row["PatientKey"]
    if string_utils.xstr(row["Visit"]) == "初診":
        case_date = row["CaseDate"].strftime("%Y-%m-%d")
        sql = f'''
            SELECT CaseKey FROM cases
            WHERE
                InsType = "健保" AND
                PatientKey = {patient_key} AND
                DATE(CaseDate) < "{case_date}"
        '''
        rows = database.select_record(sql)
        if len(rows) <= 0:  # 真的沒來過
            return "初診照護"

    visit_year = 2  # 2年內無看診
    case_key = row["CaseKey"]
    current_case_date = row["CaseDate"]  # 假設這是 datetime 物件

    # 1. 計算兩年前的同一天
    # 處理閏年 2/29 的特殊情況，若兩年前沒那天，則取 3/1
    try:
        years_ago = current_case_date.replace(year=current_case_date.year - visit_year)
    except ValueError:
        years_ago = current_case_date.replace(
            year=current_case_date.year - visit_year, month=3, day=1
        )

    years_ago_str = years_ago.strftime("%Y-%m-%d")
