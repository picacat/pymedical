# 取得門診負擔 (treat_type 取代 treatment的原因: 掛號時須取得門診負擔, 以treat_type代表)
def get_diag_share_code(
    database, share_type, treatment, course, drug_fee, case_row=None
):
    if share_type == "中低收入戶":
        share_type = "基層醫療"

    diag_share_code = ""
    course_type = get_course_type(course)

    if treatment in ACUPUNCTURE_TREAT:
        treatment = "針灸治療"
    elif treatment in ACUPUNCTURE_MERGE_TREAT:
        treatment = "針灸治療"
    elif treatment in MASSAGE_TREAT:
        treatment = "傷科治療"
    else:
        treatment = "內科"

    sql = f'''
        SELECT * FROM charge_settings
        WHERE
            ChargeType = "門診負擔" AND
            ShareType = "{share_type}" AND
            TreatType = "{treatment}" AND
            Course = "{course_type}"
    '''
    try:
        row = database.select_record(sql)[0]
    except IndexError:
        return diag_share_code

