    if (
        treat_type in HOME_CARE
        and regist_type not in TOUR_TYPE
        and share_type in ["基層醫療"]
    ):
        if drug_fee > 0:  # 開藥
            diag_share_code = "K20"
        else:
            diag_share_code = "K00"

    return diag_share_code


