def get_treatment(database, case_key, primary_treatment, second_treatment, course):
    if second_treatment in ["", None]:
        return primary_treatment

    if primary_treatment == "中度複雜性針灸":
        primary_treatment = "中度針灸"
    elif primary_treatment == "高度複雜性針灸":
        primary_treatment = "高度針灸"
    elif primary_treatment == "中度複雜性針灸合併特殊疾病":
        primary_treatment = "中度針灸合併特殊疾病"

    if second_treatment == "中度複雜性傷科":
        second_treatment = "中度傷科"
    elif second_treatment == "高度複雜性傷科":
        second_treatment = "高度傷科"
    elif second_treatment == "中度複雜性傷科合併特殊疾病":
        second_treatment = "中度傷科合併特殊疾病"

    new_treatment = f"{primary_treatment}合併{second_treatment}"

    if second_treatment in ["中度傷科"] and course >= 2:
        new_treatment += "療程2-6次"
    elif second_treatment in [
        "高度傷科",
        "中度傷科合併特殊疾病",
        "脫臼整復復位",
        "骨折復位",
    ]:
        if course <= 1:
            first_treatment = new_treatment + "起始次"

            sql = f"""
                SELECT CaseDate, PatientKey FROM cases
                WHERE
                    CaseKey = {case_key}
            """
            rows = database.select_record(sql)
            if len(rows) <= 0:
                return first_treatment

            row = rows[0]
            case_date = row["CaseDate"].date()
            patient_key = row["PatientKey"]

            start_date = case_date - datetime.timedelta(days=90)
            sql = f'''
                SELECT CaseDate FROM cases
                WHERE
                    DATE(CaseDate) >= "{start_date}" AND
                    DATE(CaseDate) < "{case_date}" AND
                    PatientKey = {patient_key} AND
                    Treatment = "{first_treatment}"
            '''
            rows = database.select_record(sql)
            if len(rows) > 0:  # 已經做過起始次
                new_treatment += "後續治療"
            else:
                new_treatment = first_treatment
        else:
            new_treatment += "後續治療"

    return new_treatment


def get_medicine_order_count(database, case_key):
    sql = f"""
        SELECT
            prescript.CaseKey
        FROM prescript
            LEFT JOIN presextend ON presextend.PrescriptKey = prescript.PrescriptKey
        WHERE
            prescript.CaseKey = {case_key} AND
            prescript.MedicineSet = 1 AND
            prescript.MedicineName NOT LIKE "%清冠一號%" AND
            prescript.InsCode IS NOT NULL AND
            presextend.ExtendType = "處方簽章" AND
            presextend.Content IS NOT NULL
    """
    rows = database.select_record(sql)

    return len(rows)


def get_home_care_card(database, patient_key, today):
    if patient_key in [None, ""]:
        return "自動取得"

    year = today[:4]
    month = today[5:7]
    first_day = datetime.date(int(year), int(month), 1).strftime("%Y-%m-%d")

    sql = f'''
        SELECT Card FROM cases
        WHERE
            PatientKey = {patient_key} AND
            DATE(CaseDate) >= "{first_day}" AND
            DATE(CaseDate) < "{today}" AND
            TreatType = "居家醫療"
        ORDER BY CaseDate LIMIT 1
    '''
    rows = database.select_record(sql)
    if len(rows) <= 0:
        return "自動取得"

    row = rows[0]
    card = string_utils.xstr(row["Card"])

    return card


