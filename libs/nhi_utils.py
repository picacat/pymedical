def get_medicine_type(database, medicine_type):
    sql = f'''
        SELECT * FROM dict_groups
        WHERE
            DictGroupsType = "{medicine_type}"''
    '''
    rows = database.select_record(sql)
    medicine_groups = []
    for row in rows:
        groups_name = row["DictGroupsName"]
        if groups_name is None:
            continue

        if medicine_type == "藥品類別" and string_utils.xstr(groups_name) in [
            "穴道",
            "處置",
            "外用",
        ]:  # 過濾自訂處方類別有與針傷處方類別相同的類別
            continue

        medicine_groups.append(row["DictGroupsName"])

    if medicine_type == "藥品類別":  # 增加處方備註
        if "備註" not in medicine_groups:
            medicine_groups.append("備註")
    elif medicine_type == "處置類別":  # 增加
        if "外用" not in medicine_groups:
            medicine_groups.append("外用")

    return medicine_groups


